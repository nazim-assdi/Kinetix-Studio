export function generateWaveformPeaks(seed: number, count: number = 96): number[] {
  const peaks: number[] = [];
  for (let i = 0; i < count; i++) {
    const wave = Math.abs(Math.sin(i * 0.37 + seed) * Math.cos(i * 0.13 + seed * 0.5));
    const beat = i % 8 === 0 ? 0.35 : i % 4 === 0 ? 0.18 : 0.05;
    peaks.push(Math.min(1, 0.18 + wave * 0.62 + beat));
  }
  return peaks;
}

